#!/usr/bin/env python3
"""Rebuild plan/key-papers.md from the "Key papers" slide of every unit.

    python3 plan/build-key-papers.py

Units are listed in the order of contentplan.md. Every citation on a Key
papers slide was verified against doi.org by the unit's author; units not yet
written keep the candidate list from the previous version (unverified).
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = re.findall(r"^\| `([a-z0-9-]+)` \|.*\| (\w+) \|[^|]*\|$", open(os.path.join(ROOT, "contentplan.md")).read(), re.M)
order = [slug for slug, _ in rows]
written = {slug for slug, status in rows if status == "written"}
old = open(os.path.join(ROOT, "plan", "key-papers.md")).read()

def old_block(slug):
    m = re.search(r"^`" + re.escape(slug) + r"`\n(.*?)(?=\n`|\n## |\Z)", old, re.S | re.M)
    return m.group(1).strip() if m else ""

out = ["# Key papers per unit", "",
       "Generated by `plan/build-key-papers.py` from the Key papers slide of each",
       "written unit (verified via doi.org by the unit's author). Units not yet",
       "written keep their **unverified** candidate list.", ""]
for slug in order:
    lec = os.path.join(ROOT, slug, "lec.qmd")
    out.append(f"`{slug}`")
    if slug in written and os.path.isfile(lec):
        s = open(lec).read()
        m = re.search(r"^## Key papers.*?\n(.*?)(?=\n## |\Z)", s, re.S | re.M)
        items = [l for l in (m.group(1).splitlines() if m else []) if l.startswith("- ")]
        for l in items:
            doi = re.search(r"https://doi\.org/([^)\s]+)", l)
            text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", l[2:]).strip()
            out.append(f"- [x] {text}" + (f" doi:{doi.group(1)}" if doi else ""))
        if not items:
            out.append("- (no Key papers slide found)")
    else:
        out.append(old_block(slug) or "- (no candidates)")
    out.append("")
open(os.path.join(ROOT, "plan", "key-papers.md"), "w").write("\n".join(out))
print(f"{len(written)} written units of {len(order)}")
